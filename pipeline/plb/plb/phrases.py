"""ESP-SR phrase list: normalize, check, assign dense command ids, emit phrases.txt/.h.

ESP-SR MultiNet (6/7, English) takes lowercase phrases made of letters and spaces.
The command id it returns is looked up in the library's command table to get the
node. The device swaps in a list of up to 200 per section, so there is no global cap.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

from .trees import Issue

MAX_PHRASES = 200
MAX_LEN = 63


def normalize(ph: str) -> str:
    s = ph.lower().replace("'", "").replace("-", " ")
    s = re.sub(r"[^a-z ]", " ", s)
    return re.sub(r" +", " ", s).strip()


def _lev(a: str, b: str) -> int:
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


@dataclass
class Command:
    cmd_id: int
    phrase: str      # normalized, what ESP-SR hears
    spoken: str      # as written in the tree, for the menu/help screen
    node: int
    always: bool = False   # in every voice list
    entry: bool = False    # opens a tree root (in every list as a section entry)
    tree: str = ""


def build_commands(node_phrases, max_phrases: int = MAX_PHRASES,
                   max_len: int = MAX_LEN) -> tuple[list[Command], list[Issue]]:
    """node_phrases: (spoken, node, where, always, tree_id, is_entry).

    The device loads one list per section (cart_voice_list): always phrases, then every
    section's entry phrases, then the current section's own. There is no global cap, but
    that guaranteed part must fit in max_phrases for every section."""
    issues: list[Issue] = []
    cmds: list[Command] = []
    seen: dict[str, Command] = {}
    for spoken, node, where, always, tree, entry in node_phrases:
        p = normalize(spoken)
        if not p:
            issues.append(Issue("error", where, f"phrase {spoken!r} is empty after normalizing"))
            continue
        if len(p) > max_len:
            issues.append(Issue("error", where, f"phrase {p!r} longer than {max_len} chars"))
            continue
        if p in seen:
            other = seen[p]
            if other.node != node:
                issues.append(Issue("error", where, f"phrase {p!r} already opens node {other.node}"))
            else:
                other.always |= always
            continue
        c = Command(len(cmds), p, spoken, node, always, entry, tree)
        seen[p] = c
        cmds.append(c)

    shared = {c.phrase for c in cmds if c.always or c.entry}
    if len(shared) > max_phrases:
        issues.append(Issue("error", "phrases", f"{len(shared)} always/entry phrases leave no room "
                                                f"in a {max_phrases}-command voice list"))
    for tree in sorted({c.tree for c in cmds}):
        need = shared | {c.phrase for c in cmds if c.tree == tree}
        if len(need) > max_phrases:
            issues.append(Issue("error", f"tree {tree}", f"voice list needs {len(need)} phrases "
                                                         f"(always + entries + own), limit {max_phrases}"))
    # only compare phrases that can be in the same list at once
    for i, a in enumerate(cmds):
        for b in cmds[i + 1:]:
            together = a.tree == b.tree or a.always or b.always or a.entry or b.entry
            if together and a.node != b.node and \
                    _lev(a.phrase, b.phrase) <= max(1, min(len(a.phrase), len(b.phrase)) // 6):
                issues.append(Issue("warning", "phrases", f"{a.phrase!r} and {b.phrase!r} sound alike "
                                                          "but open different nodes"))
    return cmds, issues


def write_phrases_txt(cmds: list[Command], path) -> None:
    """One `id<TAB>phrase` per line, for esp_mn_commands_add() or menuconfig import."""
    path.write_text("".join(f"{c.cmd_id}\t{c.phrase}\n" for c in cmds))


def write_phrases_h(cmds: list[Command], path) -> None:
    rows = "\n".join(f'    {{{c.cmd_id}, "{c.phrase}"}},' for c in cmds)
    path.write_text(f"""/* Generated by plb build. Do not edit. */
#pragma once
typedef struct {{ int id; const char *phrase; }} plb_phrase_t;
static const plb_phrase_t PLB_PHRASES[] = {{
{rows}
}};
#define PLB_PHRASE_COUNT {len(cmds)}
/* Register with: for (i..) esp_mn_commands_add(PLB_PHRASES[i].id, PLB_PHRASES[i].phrase);
   then esp_mn_commands_update(). The recognised id indexes the library's command table. */
""")
