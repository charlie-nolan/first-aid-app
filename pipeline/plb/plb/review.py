"""`plb review`: one Markdown page per tree showing exactly what the device will show,
so a person can vet every passage against the manual before it ships."""
from __future__ import annotations

import json
from pathlib import Path


def write_review(inter: Path, out_dir: Path) -> list[Path]:
    trees = json.loads((inter / "trees.json").read_text())
    passages = {json.loads(l)["id"]: json.loads(l)
                for l in (inter / "passages.jsonl").read_text().splitlines() if l}
    pics = {p["id"]: p for p in json.loads((inter / "pictures.json").read_text())}
    phrases = json.loads((inter / "phrases.json").read_text())
    nodes = {n["id"]: n for n in trees["nodes"]}
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for t in trees["trees"]:
        lines = [f"# {t['title']} ({t['shelf']}{', emergency' if t['emergency'] else ''})", "",
                 "Review copy generated by `plb review`. Text in quote blocks is verbatim from the "
                 "cited manual; only the headings and choice labels were written by hand.", ""]
        if t.get("tags"):
            lines += [f"Tags: `{json.dumps(t['tags'])}`", ""]
        for n in [x for x in trees["nodes"] if x["tree"] == t["id"]]:
            say = [p["phrase"] for p in phrases if p["node"] == n["id"]]
            lines += [f"## {n['label']}  `{n['key']}`", ""]
            if say:
                lines += [f"Voice: {', '.join(say)}", ""]
            if n["figure"] and n["figure"] in pics:
                p = pics[n["figure"]]
                lines += [f"Picture: {p['caption']} ({p['citation']}, {p['w']}x{p['h']}"
                          f"{', pans' if p['pan'] else ''})", ""]
            for pid in n["passages"] + n["lookalikes"]:
                p = passages[pid]
                body = "\n".join("> " + l if l else ">" for l in p["text"].split("\n"))
                lines += [f"**{p['citation']}**" + (f" ({p['heading']})" if "~" in pid else ""),
                          "", body, ""]
            for c in n["choices"]:
                lines.append(f"- [{c['kind']}] {c['label']} -> `{nodes[c['to']]['key']}`")
            lines.append("")
        f = out_dir / f"{t['id']}.md"
        f.write_text("\n".join(lines))
        written.append(f)
    return written
